const Font = {
  smallWidth: (s, sc = 1) => Math.max(0, s.length * 4 - 1) * sc,
  bigWidth: (s, sc = 1) => Math.max(0, s.length * 6 - 1) * sc,

  small(ctx, str, x, y, color, sc = 1, shadow) {
    str = String(str).toUpperCase();
    if (shadow) Font.small(ctx, str, x + 1, y + 1, shadow, sc);
    ctx.fillStyle = color;
    for (let i = 0; i < str.length; i++) {
      const g = SMALL[str[i]] || SMALL[' '];
      for (let p = 0; p < 15; p++) if (g[p] === '1') ctx.fillRect(x + (i * 4 + p % 3) * sc, y + Math.floor(p / 3) * sc, sc, sc);
    }
  },

  big(ctx, str, x, y, color, sc = 1, outline) {
    str = String(str).toUpperCase();
    const plot = (col, ox, oy) => {
      ctx.fillStyle = col;
      for (let i = 0; i < str.length; i++) {
        const g = BIG[str[i]] || BIG[' '];
        for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++)
          if (g[r][c] === '1') ctx.fillRect(x + (i * 6 + c) * sc + ox, y + r * sc + oy, sc, sc);
      }
    };
    if (outline) for (const [ox, oy] of [[-1,0],[1,0],[0,-1],[0,1],[1,1],[2,2],[1,2],[2,1]]) plot(outline, ox, oy);
    plot(color, 0, 0);
  },

  smallCentered(ctx, str, cx, y, color, sc = 1, shadow) { Font.small(ctx, str, Math.round(cx - Font.smallWidth(String(str), sc) / 2), y, color, sc, shadow); },
  bigCentered(ctx, str, cx, y, color, sc = 1, outline) { Font.big(ctx, str, Math.round(cx - Font.bigWidth(String(str), sc) / 2), y, color, sc, outline); },

  // greedy word wrap for the 3x5 font
  wrap(str, maxW, sc = 1) {
    const words = String(str).toUpperCase().split(/\s+/), lines = [];
    let line = '';
    for (const w of words) {
      const t = line ? line + ' ' + w : w;
      if (Font.smallWidth(t, sc) > maxW && line) { lines.push(line); line = w; } else line = t;
    }
    if (line) lines.push(line);
    return lines;
  },
};
